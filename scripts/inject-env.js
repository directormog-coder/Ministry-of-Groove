#!/usr/bin/env node
/**
 * Ministry of Groove - Environment Variable Injector
 * Injects secure env vars into HTML/JS files at build time
 * 
 * SECURITY: This script runs server-side on Vercel only
 * No secrets are exposed in client-side code or repository
 * 
 * Build Command: node scripts/build-inject.js
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// ==========================================
// CONFIGURATION
// ==========================================

const CONFIG = {
    // Source templates directory (original files)
    sourceDir: './src',
    // Output directory (processed files)
    outputDir: './dist',
    // Files to process
    files: [
        'login.html',
        'index.html',
        'hub.html',
        'directorate.html',
        'js/supabase-config.js',
        'js/auth.js'
    ],
    // Security: No Apple Sign In variables removed
    placeholders: {
        SUPABASE_URL: process.env.SUPABASE_URL,
        SUPABASE_ANON_KEY: process.env.SUPABASE_ANON_KEY,
        GOOGLE_CLIENT_ID: process.env.GOOGLE_CLIENT_ID || '',
        APP_VERSION: process.env.npm_package_version || '5.2.0',
        BUILD_TIMESTAMP: new Date().toISOString(),
        BUILD_HASH: crypto.randomBytes(8).toString('hex')
    }
};

// ==========================================
// VALIDATION
// ==========================================

function validateEnvironment() {
    const required = ['SUPABASE_URL', 'SUPABASE_ANON_KEY'];
    const missing = required.filter(key => !CONFIG.placeholders[key]);
    
    if (missing.length > 0) {
        console.error('❌ CRITICAL ERROR: Missing required environment variables:');
        missing.forEach(key => console.error(`   - ${key}`));
        console.error('\n💡 Add these in Vercel Dashboard:');
        console.error('   Project Settings > Environment Variables\n');
        console.error('🔒 Security: Build cannot proceed without secure credentials');
        process.exit(1);
    }

    // Validate URL format
    try {
        new URL(CONFIG.placeholders.SUPABASE_URL);
    } catch (e) {
        console.error('❌ Invalid SUPABASE_URL format');
        process.exit(1);
    }

    console.log('✅ Environment variables validated');
    console.log(`🔧 Build Version: ${CONFIG.placeholders.APP_VERSION}`);
    console.log(`⏰ Timestamp: ${CONFIG.placeholders.BUILD_TIMESTAMP}\n`);
}

// ==========================================
// FILE PROCESSING
// ==========================================

function ensureDirectoryExists(filePath) {
    const dirname = path.dirname(filePath);
    if (fs.existsSync(dirname)) return true;
    fs.mkdirSync(dirname, { recursive: true });
}

function removeAppleSignInCode(content, fileName) {
    // Remove Apple Sign In HTML buttons
    content = content.replace(
        /<button[^>]*apple[^>]*sign[^>]*in[^>]*>[\s\S]*?<\/button>/gi,
        ''
    );
    
    // Remove Apple Sign In JavaScript initialization
    content = content.replace(
        /\/\/\s*Apple\s*Sign\s*In[\s\S]*?(?=\/\/\s*End\s*Apple|\n\/\/|\nfunction|\nclass|$)/gi,
        ''
    );
    
    // Remove Apple ID SDK script tags
    content = content.replace(
        /<script[^>]*appleid\.cdn-apple\.com[^>]*><\/script>/gi,
        ''
    );
    
    // Remove Apple Sign In event listeners
    content = content.replace(
        /document\.addEventListener[^}]*AppleID[^}]*}\);/gi,
        ''
    );
    
    // Remove Apple Sign In configuration objects
    content = content.replace(
        /const\s+appleAuthConfig\s*=\s*{[^}]*}/gi,
        ''
    );
    
    // Remove standalone Apple Sign In functions
    content = content.replace(
        /async\s+function\s+(handleAppleSignIn|initAppleAuth|appleLogin)[^{]*{[^}]*}/gi,
        ''
    );

    // Clean up any leftover Apple-specific comments
    content = content.replace(/<!--\s*Apple[^>]*-->/gi, '');
    content = content.replace(/\/\/\s*Apple.*$/gim, '');

    return content;
}

function injectSecurityHeaders(content, fileName) {
    if (!fileName.endsWith('.html')) return content;

    const cspNonce = crypto.randomBytes(16).toString('base64');
    
    const securityMeta = `
    <!-- 
    MINISTRY OF GROOVE v${CONFIG.placeholders.APP_VERSION}
    Build: ${CONFIG.placeholders.BUILD_TIMESTAMP}
    Hash: ${CONFIG.placeholders.BUILD_HASH}
    Security: Environment variables injected at build time
    Nonce: ${cspNonce}
    WARNING: Do not edit this file directly - modify source templates
    -->
    <meta http-equiv="Content-Security-Policy" content="
        default-src 'self';
        script-src 'self' 'nonce-${cspNonce}' https://cdn.tailwindcss.com https://unpkg.com https://cdn.jsdelivr.net;
        style-src 'self' 'unsafe-inline' https://fonts.googleapis.com;
        font-src 'self' https://fonts.gstatic.com;
        connect-src 'self' ${CONFIG.placeholders.SUPABASE_URL} https://*.supabase.co;
        img-src 'self' data: https:;
        frame-ancestors 'none';
        base-uri 'self';
        form-action 'self';
    ">
    <meta name="referrer" content="strict-origin-when-cross-origin">
    <meta http-equiv="X-Content-Type-Options" content="nosniff">
    <meta http-equiv="X-Frame-Options" content="DENY">
    `;

    // Insert after <head> tag
    return content.replace(/<head>/i, `<head>\n${securityMeta}`);
}

function processFile(fileName) {
    const sourcePath = path.join(CONFIG.sourceDir, fileName);
    const outputPath = path.join(CONFIG.outputDir, fileName);
    
    // Check source exists
    if (!fs.existsSync(sourcePath)) {
        console.log(`⚠️  Skipping ${fileName} (source not found in ${CONFIG.sourceDir})`);
        return false;
    }
    
    let content = fs.readFileSync(sourcePath, 'utf8');
    let modified = false;
    
    // Step 1: Remove Apple Sign In code
    const originalLength = content.length;
    content = removeAppleSignInCode(content, fileName);
    if (content.length !== originalLength) {
        console.log(`🍎 Removed Apple Sign In code from ${fileName}`);
        modified = true;
    }
    
    // Step 2: Replace environment placeholders
    Object.entries(CONFIG.placeholders).forEach(([key, value]) => {
        const placeholder = new RegExp(`{{${key}}}`, 'g');
        if (content.includes(`{{${key}}}`)) {
            content = content.replace(placeholder, value);
            modified = true;
        }
    });
    
    // Step 3: Inject security headers for HTML files
    if (fileName.endsWith('.html')) {
        content = injectSecurityHeaders(content, fileName);
        modified = true;
    }
    
    // Step 4: Write output
    ensureDirectoryExists(outputPath);
    fs.writeFileSync(outputPath, content);
    
    if (modified) {
        console.log(`✅ Processed ${fileName} → ${outputPath}`);
    } else {
        console.log(`⏩ Copied ${fileName} (no changes)`);
    }
    
    return true;
}

// ==========================================
// CLEANUP & UTILITIES
// ==========================================

function cleanupLegacyFiles() {
    const legacyFiles = [
        './login.html',
        './index.html',
        './hub.html',
        './directorate.html',
        './js/supabase-config.js'
    ];
    
    legacyFiles.forEach(file => {
        if (fs.existsSync(file) && !file.startsWith(CONFIG.outputDir)) {
            try {
                fs.unlinkSync(file);
                console.log(`🗑️  Cleaned up legacy file: ${file}`);
            } catch (e) {
                // Ignore errors
            }
        }
    });
}

function generateBuildManifest() {
    const manifest = {
        version: CONFIG.placeholders.APP_VERSION,
        timestamp: CONFIG.placeholders.BUILD_TIMESTAMP,
        buildHash: CONFIG.placeholders.BUILD_HASH,
        features: {
            appleSignIn: false,
            googleSignIn: !!CONFIG.placeholders.GOOGLE_CLIENT_ID,
            emailAuth: true,
            supabaseAuth: true
        },
        security: {
            cspEnabled: true,
            nonceGenerated: true,
            envVarsInjected: ['SUPABASE_URL', 'SUPABASE_ANON_KEY']
        }
    };
    
    const manifestPath = path.join(CONFIG.outputDir, 'build-manifest.json');
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
    console.log(`📋 Build manifest generated`);
}

// ==========================================
// MAIN EXECUTION
// ==========================================

console.log('🔐 Ministry of Groove - Secure Build Process');
console.log('==========================================');
console.log('🛡️  Apple Sign In: REMOVED');
console.log('🔧 Environment Injection: ENABLED\n');

try {
    // Validate first
    validateEnvironment();
    
    // Ensure output directory exists
    if (!fs.existsSync(CONFIG.outputDir)) {
        fs.mkdirSync(CONFIG.outputDir, { recursive: true });
    }
    
    // Process all files
    let processedCount = 0;
    CONFIG.files.forEach(file => {
        if (processFile(file)) processedCount++;
    });
    
    // Cleanup old files in root
    cleanupLegacyFiles();
    
    // Generate manifest
    generateBuildManifest();
    
    console.log(`\n✨ Build complete! ${processedCount} files processed.`);
    console.log(`📁 Output: ${path.resolve(CONFIG.outputDir)}`);
    console.log(`🔒 Security: All secrets injected server-side only.`);
    console.log(`🍎 Apple Sign In: Successfully removed from all files.`);
    
} catch (error) {
    console.error('\n❌ Build failed:', error.message);
    console.error(error.stack);
    process.exit(1);
}

#!/usr/bin/env node
/**
 * Ministry of Groove - Environment Variable Injector
 * Injects secure env vars into HTML/JS files at build time
 * 
 * SECURITY: This script runs server-side on Vercel only
 * No secrets are exposed in client-side code or repository
 */

const fs = require('fs');
const path = require('path');

// Configuration
const CONFIG = {
    files: [
        'login.html',
        'index.html',
        'js/supabase-config.js'
    ],
    placeholders: {
        SUPABASE_URL: process.env.SUPABASE_URL || 'https://fgkljjgxecjmiiaptiug.supabase.co',
        SUPABASE_ANON_KEY: process.env.SUPABASE_ANON_KEY,
        APPLE_SERVICES_ID: process.env.APPLE_SERVICES_ID || '',
        APPLE_REDIRECT_URI: process.env.APPLE_REDIRECT_URI || 'https://ministry-of-groove.vercel.app/auth/callback',
        APP_VERSION: process.env.npm_package_version || '5.1.0',
        BUILD_TIMESTAMP: new Date().toISOString()
    }
};

// Validate critical environment variables
function validateEnvironment() {
    const required = ['SUPABASE_ANON_KEY'];
    const missing = required.filter(key => !CONFIG.placeholders[key]);
    
    if (missing.length > 0) {
        console.error('❌ CRITICAL ERROR: Missing required environment variables:');
        missing.forEach(key => console.error(`   - ${key}`));
        console.error('\n💡 Add these in Vercel Dashboard: Project Settings > Environment Variables');
        process.exit(1);
    }
}

// Process single file
function processFile(filePath) {
    const fullPath = path.join(process.cwd(), filePath);
    
    if (!fs.existsSync(fullPath)) {
        console.log(`⚠️  Skipping ${filePath} (not found)`);
        return false;
    }
    
    let content = fs.readFileSync(fullPath, 'utf8');
    let modified = false;
    
    // Replace all placeholders
    Object.entries(CONFIG.placeholders).forEach(([key, value]) => {
        const placeholder = new RegExp(`{{${key}}}`, 'g');
        if (content.includes(`{{${key}}}`)) {
            content = content.replace(placeholder, value);
            modified = true;
        }
    });
    
    // Add security headers comment if HTML
    if (filePath.endsWith('.html') && modified) {
        const securityComment = `<!-- 
    MINISTRY OF GROOVE v${CONFIG.placeholders.APP_VERSION}
    Build: ${CONFIG.placeholders.BUILD_TIMESTAMP}
    Security: Environment variables injected at build time
    WARNING: Do not edit this file directly - modify source templates
-->\n`;
        content = securityComment + content;
    }
    
    fs.writeFileSync(fullPath, content);
    console.log(`✅ Injected env vars into ${filePath}`);
    return true;
}

// Main execution
console.log('🔐 Ministry of Groove - Secure Build Process');
console.log('==========================================\n');

try {
    validateEnvironment();
    
    let processedCount = 0;
    CONFIG.files.forEach(file => {
        if (processFile(file)) processedCount++;
    });
    
    console.log(`\n✨ Build complete! ${processedCount} files processed.`);
    console.log(`🔒 Security: All secrets injected server-side only.`);
    
} catch (error) {
    console.error('\n❌ Build failed:', error.message);
    process.exit(1);
}
